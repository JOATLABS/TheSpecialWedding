"""Durable, low-cardinality operations signals for storefront domains.

The reconciliation worker polls the same domain many times while DNS and
certificate state converges.  This helper turns only material incident
transitions into root-admin notifications and counters, while exposing the
current queue depth and oldest due work as gauges.

Customer hostnames and planner identifiers never enter notifications or metric
tags.  Operators correlate an incident through the public support ID and an
opaque, one-way domain reference.
"""

from __future__ import annotations

import hashlib
import logging
from collections.abc import Callable, Iterable, Mapping
from dataclasses import dataclass
from datetime import UTC, datetime, timedelta
from typing import Any

from bson import ObjectId

from app.constants.storefront_domain import (
    ACTION_REQUIRED,
    DISCONNECT_FAILED,
    OPERATOR_REVIEW,
)

logger = logging.getLogger(__name__)

_ALERT_RETRY_DELAY = timedelta(minutes=1)
_BACKLOG_SAMPLE_LIMIT = 100
_BACKLOG_ALERT_COUNT = 100
_BACKLOG_ALERT_AGE = timedelta(minutes=15)
_BACKLOG_SUPPORT_ID = "sfd_storefront_domain_backlog"
_DOMAIN_COLLECTION = "storefront_domains"
_CONFLICT_COLLECTION = "storefront_domain_conflict_claims"
_ALERT_CATEGORIES = frozenset(
    {
        "operator_review",
        "disconnect_failed",
        "action_required",
        "provider_rate_limited",
        "provider_server_error",
    }
)


@dataclass(frozen=True)
class StorefrontDomainIncident:
    """Sanitized incident identity used for dedupe, alerts, and metrics."""

    category: str
    phase: str
    support_id: str
    error_code: str
    provider_status_code: int | None = None
    provider_operation: str | None = None

    @property
    def signature(self) -> str:
        """Stable while a polled failure remains materially unchanged.

        Support IDs may be regenerated by a provider observation.  Keeping the
        transition signature independent from that value prevents a polling
        loop from emitting a new alert for the same unresolved condition.  The
        durable alert identity itself still binds domain, phase, and the first
        observed support ID.
        """

        provider_class = (
            "429"
            if self.provider_status_code == 429
            else (
                "5xx"
                if self.provider_status_code is not None
                and 500 <= self.provider_status_code <= 599
                else str(self.provider_status_code or "")
            )
        )
        return "/".join(
            (
                self.category,
                self.phase,
                self.error_code,
                provider_class,
                self.provider_operation or "",
            )
        )


def _aware(value: object) -> datetime | None:
    if not isinstance(value, datetime):
        return None
    return value if value.tzinfo else value.replace(tzinfo=UTC)


def _mapping(value: object) -> Mapping[str, Any]:
    return value if isinstance(value, Mapping) else {}


def _integer(value: object) -> int | None:
    if isinstance(value, bool):
        return None
    if isinstance(value, int):
        return value
    if isinstance(value, str) and value.isdigit():
        return int(value)
    return None


class StorefrontDomainOperationalMonitor:
    """Emit idempotent operator incidents plus bounded worker metrics."""

    def __init__(
        self,
        *,
        mongo_client: Any,
        now: Callable[[], datetime] | None = None,
        counter: Callable[..., Any] | None = None,
        gauge: Callable[..., Any] | None = None,
    ) -> None:
        self._mongo = mongo_client
        self._now = now or (lambda: datetime.now(UTC))
        self._counter = counter
        self._gauge = gauge

    @staticmethod
    def _metric_id(kind: str, name: str, tags: Mapping[str, str]) -> str:
        tag_key = ",".join(f"{key}={tags[key]}" for key in sorted(tags))
        return f"{kind}:{name}:{tag_key}"

    async def _increment_metric(self, name: str, **tags: str) -> None:
        """Persist a bounded counter and optionally forward it to a runtime sink."""

        now = self._now()
        await self._mongo.db["storefront_domain_operational_metrics"].update_one(
            {"_id": self._metric_id("counter", name, tags)},
            {
                "$set": {
                    "kind": "counter",
                    "name": name,
                    "tags": dict(tags),
                    "updated_at": now,
                },
                "$setOnInsert": {"created_at": now},
                "$inc": {"value": 1},
            },
            upsert=True,
        )
        if self._counter is not None:
            self._counter(name, **tags)

    async def _set_metric(self, name: str, value: float, **tags: str) -> None:
        """Persist one fixed-cardinality gauge snapshot."""

        now = self._now()
        await self._mongo.db["storefront_domain_operational_metrics"].update_one(
            {"_id": self._metric_id("gauge", name, tags)},
            {
                "$set": {
                    "kind": "gauge",
                    "name": name,
                    "tags": dict(tags),
                    "value": value,
                    "updated_at": now,
                },
                "$setOnInsert": {"created_at": now},
            },
            upsert=True,
        )
        if self._gauge is not None:
            self._gauge(name, value, **tags)

    @staticmethod
    def _backlog_alert_id() -> ObjectId:
        digest = hashlib.sha256(
            (f"storefront-domain-alert/worker/backlog/{_BACKLOG_SUPPORT_ID}").encode()
        ).hexdigest()
        return ObjectId(digest[:24])

    async def _observe_backlog_alert(self, count: int, oldest_age: float) -> None:
        """Maintain one resumable root-admin alert for an unhealthy queue."""

        alerts = self._mongo.db["notifications"]
        alert_id = self._backlog_alert_id()
        existing = await alerts.find_one({"_id": alert_id})
        breached = count >= _BACKLOG_ALERT_COUNT or oldest_age >= (
            _BACKLOG_ALERT_AGE.total_seconds()
        )
        if not breached:
            if existing and existing.get("status") == "active":
                await alerts.update_one(
                    {"_id": alert_id, "status": "active"},
                    {
                        "$set": {
                            "status": "resolved",
                            "updated_at": self._now(),
                            "metadata.resolved_at": self._now(),
                            "metadata.backlog_count": count,
                            "metadata.oldest_age_seconds": oldest_age,
                        }
                    },
                )
            return

        message = (
            "The storefront custom-domain reconciliation queue is outside its "
            f"operating threshold. Pending: {count}. Oldest due work: "
            f"{int(oldest_age)} seconds. Support ID: {_BACKLOG_SUPPORT_ID}. "
            "Check worker health and provider failures before retrying customer operations."
        )
        metadata = {
            "source": "storefront_domain_reconciliation",
            "auto_generated": True,
            "event_key": hashlib.sha256(
                (
                    f"storefront-domain-alert/worker/backlog/{_BACKLOG_SUPPORT_ID}"
                ).encode()
            ).hexdigest(),
            "domain_reference": "worker",
            "category": "worker_backlog",
            "phase": "backlog",
            "support_id": _BACKLOG_SUPPORT_ID,
            "backlog_count": count,
            "oldest_age_seconds": oldest_age,
            "count_threshold": _BACKLOG_ALERT_COUNT,
            "age_threshold_seconds": _BACKLOG_ALERT_AGE.total_seconds(),
        }
        if existing and existing.get("status") == "active":
            await alerts.update_one(
                {"_id": alert_id, "status": "active"},
                {
                    "$set": {
                        "message": message,
                        "updated_at": self._now(),
                        "metadata": metadata,
                    }
                },
            )
            return

        now = self._now()
        await alerts.update_one(
            {"_id": alert_id},
            {
                "$set": {
                    "title": "Storefront domain worker backlog",
                    "message": message,
                    "type": "storefront_domain_operations",
                    "target_audience": "root_admin",
                    "created_by": "system",
                    "updated_at": now,
                    "is_dismissible": True,
                    "priority": "high",
                    "status": "active",
                    "read_by": [],
                    "dismissed_by": [],
                    "action_url": "/admin",
                    "metadata": metadata,
                },
                "$setOnInsert": {"created_at": now},
            },
            upsert=True,
        )
        await self._increment_metric(
            "storefront.domain.worker_backlog_alert",
            threshold="count_or_age",
        )

    @staticmethod
    def _domain_reference(domain_id: object) -> str:
        digest = hashlib.sha256(str(domain_id).encode("utf-8")).hexdigest()
        return f"sfdomain_{digest[:12]}"

    @staticmethod
    def _support_id(record: Mapping[str, Any], category: str, phase: str) -> str:
        last_error = _mapping(record.get("last_error"))
        value = last_error.get("support_id")
        if isinstance(value, str) and value.strip():
            return value.strip()[:128]
        digest = hashlib.sha256(
            "/".join(
                (
                    str(record.get("_id")),
                    category,
                    phase,
                    str(record.get("revision") or ""),
                    str(last_error.get("code") or "unknown"),
                )
            ).encode("utf-8")
        ).hexdigest()
        return f"sfd_internal_{digest[:16]}"

    @staticmethod
    def _provider_failure(record: Mapping[str, Any]) -> tuple[int | None, str | None]:
        provider_error = _mapping(record.get("provider_last_error"))
        last_error_provider = _mapping(
            _mapping(record.get("last_error")).get("provider")
        )
        status_code = _integer(
            provider_error.get("provider_status_code")
            or provider_error.get("status_code")
            or last_error_provider.get("status_code")
        )
        operation = provider_error.get("operation") or last_error_provider.get(
            "operation"
        )
        return (
            status_code,
            str(operation)[:80] if isinstance(operation, str) and operation else None,
        )

    @classmethod
    def _incidents(cls, record: Mapping[str, Any]) -> list[StorefrontDomainIncident]:
        phase = str(record.get("application_status") or "unknown")
        last_error = _mapping(record.get("last_error"))
        error_code = str(last_error.get("code") or "unknown")[:120]
        provider_status, provider_operation = cls._provider_failure(record)

        primary_category: str | None = None
        if phase == OPERATOR_REVIEW:
            primary_category = "operator_review"
        elif phase == DISCONNECT_FAILED:
            primary_category = "disconnect_failed"
        elif phase == ACTION_REQUIRED:
            primary_category = "action_required"

        incidents: list[StorefrontDomainIncident] = []
        if primary_category:
            incidents.append(
                StorefrontDomainIncident(
                    category=primary_category,
                    phase=phase,
                    support_id=cls._support_id(record, primary_category, phase),
                    error_code=error_code,
                    provider_status_code=provider_status,
                    provider_operation=provider_operation,
                )
            )

        provider_category = (
            "provider_rate_limited"
            if provider_status == 429
            else (
                "provider_server_error"
                if provider_status is not None and 500 <= provider_status <= 599
                else None
            )
        )
        # A state-level alert already carries the provider outcome.  Still emit
        # its dedicated low-cardinality metric below, but avoid two root-admin
        # notifications for one transition.
        if provider_category and not primary_category:
            incidents.append(
                StorefrontDomainIncident(
                    category=provider_category,
                    phase=phase,
                    support_id=cls._support_id(record, provider_category, phase),
                    error_code=error_code,
                    provider_status_code=provider_status,
                    provider_operation=provider_operation,
                )
            )
        return incidents

    @staticmethod
    def _event_key(
        domain_id: object,
        incident: StorefrontDomainIncident,
    ) -> str:
        return hashlib.sha256(
            "/".join(
                (
                    "storefront-domain-alert",
                    str(domain_id),
                    incident.phase,
                    incident.support_id,
                    incident.category,
                )
            ).encode("utf-8")
        ).hexdigest()

    @staticmethod
    def _notification_id(event_key: str) -> ObjectId:
        return ObjectId(event_key[:24])

    @staticmethod
    def _alert_copy(incident: StorefrontDomainIncident) -> tuple[str, str]:
        if incident.category == "operator_review":
            return (
                "Storefront domain needs operator review",
                "A storefront custom-domain record entered operator review.",
            )
        if incident.category == "disconnect_failed":
            return (
                "Storefront domain cleanup failed",
                "A storefront custom-domain disconnect needs cleanup recovery.",
            )
        if incident.category == "action_required":
            return (
                "Storefront domain activation needs attention",
                "A storefront custom domain failed a routing, certificate, or secure-response check.",
            )
        if incident.category == "provider_rate_limited":
            return (
                "Storefront domain provider rate limited",
                "The custom-domain provider rate-limited a storefront operation.",
            )
        return (
            "Storefront domain provider unavailable",
            "The custom-domain provider returned a server failure during reconciliation.",
        )

    async def _claim_incident(
        self,
        record: Mapping[str, Any],
        incident: StorefrontDomainIncident,
        event_key: str,
        *,
        collection_name: str = _DOMAIN_COLLECTION,
    ) -> bool:
        marker_path = f"operational_alerts.{incident.category}"
        now = self._now()
        snapshot_filter: dict[str, Any] = {
            "_id": record.get("_id"),
            "application_status": incident.phase,
        }
        observed_support_id = _mapping(record.get("last_error")).get("support_id")
        if isinstance(observed_support_id, str) and observed_support_id:
            snapshot_filter["last_error.support_id"] = observed_support_id
        elif incident.error_code != "unknown":
            snapshot_filter["last_error.code"] = incident.error_code
        result = await self._mongo.db[collection_name].update_one(
            {
                **snapshot_filter,
                "$or": [
                    {f"{marker_path}.active": {"$ne": True}},
                    {f"{marker_path}.signature": {"$ne": incident.signature}},
                    {
                        f"{marker_path}.delivery_status": "pending",
                        f"{marker_path}.next_attempt_at": {"$lte": now},
                    },
                ],
            },
            {
                "$set": {
                    marker_path: {
                        "active": True,
                        "signature": incident.signature,
                        "phase": incident.phase,
                        "support_id": incident.support_id,
                        "event_key": event_key,
                        "delivery_status": "pending",
                        "observed_at": now,
                        "next_attempt_at": now + _ALERT_RETRY_DELAY,
                    }
                }
            },
        )
        return bool(getattr(result, "matched_count", 0))

    async def _emit_incident(
        self,
        record: Mapping[str, Any],
        incident: StorefrontDomainIncident,
        *,
        collection_name: str = _DOMAIN_COLLECTION,
    ) -> None:
        domain_id = record.get("_id")
        if domain_id is None:
            return
        event_key = self._event_key(domain_id, incident)
        if not await self._claim_incident(
            record,
            incident,
            event_key,
            collection_name=collection_name,
        ):
            return

        reference = self._domain_reference(domain_id)
        title, summary = self._alert_copy(incident)
        provider_outcome = (
            f" Provider status: {incident.provider_status_code}."
            if incident.provider_status_code is not None
            else ""
        )
        message = (
            f"{summary} Reference: {reference}. Phase: {incident.phase}. "
            f"Support ID: {incident.support_id}.{provider_outcome} "
            "Review the storefront-domain operations evidence before retrying or changing DNS."
        )
        metadata = {
            "source": "storefront_domain_reconciliation",
            "auto_generated": True,
            "event_key": event_key,
            "domain_reference": reference,
            "category": incident.category,
            "phase": incident.phase,
            "support_id": incident.support_id,
            "error_code": incident.error_code,
            "provider_status_code": incident.provider_status_code,
            "provider_operation": incident.provider_operation,
        }
        notification = {
            "_id": self._notification_id(event_key),
            "title": title,
            "message": message,
            "type": "storefront_domain_operations",
            "target_audience": "root_admin",
            "created_by": "system",
            "created_at": self._now(),
            "updated_at": self._now(),
            "is_dismissible": True,
            "priority": "high",
            "status": "active",
            "read_by": [],
            "dismissed_by": [],
            # The notification remains free of tenant/hostname identifiers.
            # Root admins resolve the exact review through the protected queue.
            "action_url": "/admin/platform?tab=storefront",
            "metadata": metadata,
        }
        alerts = self._mongo.db["notifications"]
        inserted = False
        try:
            await alerts.insert_one(notification)
            existing = notification
            inserted = True
        except Exception:
            existing = await alerts.find_one({"_id": notification["_id"]})
            if not existing:
                logger.exception(
                    "Failed to persist storefront-domain operator alert",
                    extra={"domain_reference": reference, "event_key": event_key},
                )
                return

        if _mapping(existing.get("metadata")).get("event_key") != event_key:
            logger.critical(
                "Deterministic storefront-domain alert ID collision",
                extra={"domain_reference": reference, "event_key": event_key},
            )
            return

        marker_path = f"operational_alerts.{incident.category}"
        await self._mongo.db[collection_name].update_one(
            {
                "_id": domain_id,
                f"{marker_path}.event_key": event_key,
                f"{marker_path}.delivery_status": "pending",
            },
            {
                "$set": {
                    f"{marker_path}.delivery_status": "visible",
                    f"{marker_path}.notification_id": str(notification["_id"]),
                    f"{marker_path}.visible_at": self._now(),
                },
                "$unset": {f"{marker_path}.next_attempt_at": ""},
            },
        )
        if inserted:
            await self._increment_metric(
                "storefront.domain.operational_alert",
                category=incident.category,
                phase=incident.phase,
            )

    async def _deactivate_resolved(
        self,
        record: Mapping[str, Any],
        active_categories: set[str],
        *,
        collection_name: str = _DOMAIN_COLLECTION,
    ) -> None:
        markers = _mapping(record.get("operational_alerts"))
        resolved_categories = [
            category
            for category in _ALERT_CATEGORIES - active_categories
            if _mapping(markers.get(category)).get("active") is True
        ]
        resolved = {
            f"operational_alerts.{category}.active": False
            for category in resolved_categories
        }
        if resolved:
            resolved.update(
                {
                    f"operational_alerts.{category}.resolved_at": self._now()
                    for category in resolved_categories
                }
            )
            await self._mongo.db[collection_name].update_one(
                {
                    "_id": record.get("_id"),
                    "application_status": record.get("application_status"),
                },
                {"$set": resolved},
            )
            # Resolve the matching root-admin receipt as well as the source
            # marker. Otherwise an operator queue can be clean while a stale,
            # actionable notification remains indefinitely.
            for category in resolved_categories:
                marker = _mapping(markers.get(category))
                notification_id = marker.get("notification_id")
                event_key = marker.get("event_key")
                if not notification_id or not event_key:
                    continue
                try:
                    alert_id = ObjectId(str(notification_id))
                except Exception:
                    continue
                await self._mongo.db["notifications"].update_one(
                    {
                        "_id": alert_id,
                        "status": "active",
                        "metadata.event_key": event_key,
                    },
                    {
                        "$set": {
                            "status": "resolved",
                            "updated_at": self._now(),
                            "metadata.resolved_at": self._now(),
                        }
                    },
                )

    async def observe_domain(self, record: Mapping[str, Any] | None) -> None:
        """Observe one persisted post-reconciliation domain snapshot."""

        if not record or record.get("_id") is None:
            return
        incidents = self._incidents(record)
        categories = {incident.category for incident in incidents}
        await self._deactivate_resolved(
            record,
            categories,
            collection_name=_DOMAIN_COLLECTION,
        )

        provider_status, _ = self._provider_failure(record)
        provider_category = (
            "rate_limited"
            if provider_status == 429
            else (
                "server_error"
                if provider_status is not None and 500 <= provider_status <= 599
                else None
            )
        )
        # Count each persisted provider outcome once even when a more specific
        # state-level notification represents the same failure.
        if provider_category:
            metric_incident = StorefrontDomainIncident(
                category=f"provider_{provider_category}",
                phase=str(record.get("application_status") or "unknown"),
                support_id=self._support_id(
                    record,
                    f"provider_{provider_category}",
                    str(record.get("application_status") or "unknown"),
                ),
                error_code=str(
                    _mapping(record.get("last_error")).get("code") or "unknown"
                ),
                provider_status_code=provider_status,
            )
            marker_path = "operational_alerts.provider_outcome_metric"
            claimed = await self._mongo.db["storefront_domains"].update_one(
                {
                    "_id": record.get("_id"),
                    "application_status": metric_incident.phase,
                    "$and": [
                        {
                            "$or": [
                                {f"{marker_path}.active": {"$ne": True}},
                                {
                                    f"{marker_path}.signature": {
                                        "$ne": metric_incident.signature
                                    }
                                },
                            ]
                        },
                        {
                            "$or": [
                                {
                                    "provider_last_error.provider_status_code": provider_status
                                },
                                {"provider_last_error.status_code": provider_status},
                                {"last_error.provider.status_code": provider_status},
                            ]
                        },
                    ],
                },
                {
                    "$set": {
                        marker_path: {
                            "active": True,
                            "signature": metric_incident.signature,
                            "observed_at": self._now(),
                        }
                    }
                },
            )
            if getattr(claimed, "matched_count", 0):
                await self._increment_metric(
                    "storefront.domain.provider_outcome",
                    outcome=provider_category,
                    phase=metric_incident.phase,
                )
        else:
            provider_metric = _mapping(
                _mapping(record.get("operational_alerts")).get(
                    "provider_outcome_metric"
                )
            )
            if provider_metric.get("active") is True:
                await self._mongo.db["storefront_domains"].update_one(
                    {
                        "_id": record.get("_id"),
                        "application_status": record.get("application_status"),
                        "provider_last_error.provider_status_code": {"$exists": False},
                        "provider_last_error.status_code": {"$exists": False},
                        "last_error.provider.status_code": {"$exists": False},
                    },
                    {
                        "$set": {
                            "operational_alerts.provider_outcome_metric.active": False,
                            "operational_alerts.provider_outcome_metric.resolved_at": self._now(),
                        }
                    },
                )

        for incident in incidents:
            await self._emit_incident(
                record,
                incident,
                collection_name=_DOMAIN_COLLECTION,
            )

    async def observe_conflict_claim(
        self,
        record: Mapping[str, Any] | None,
    ) -> None:
        """Publish the same sanitized review signal for verified claim conflicts.

        Conflict claims live outside ``storefront_domains`` and are intentionally
        append-only. They still enter the protected operator queue, so omitting
        them from operational alerting would strand a real customer review with
        no root-admin signal.
        """

        if not record or record.get("_id") is None:
            return
        incidents = self._incidents(record)
        categories = {incident.category for incident in incidents}
        await self._deactivate_resolved(
            record,
            categories,
            collection_name=_CONFLICT_COLLECTION,
        )
        for incident in incidents:
            await self._emit_incident(
                record,
                incident,
                collection_name=_CONFLICT_COLLECTION,
            )

    async def observe_conflict_reviews(self, *, limit: int = 100) -> int:
        """Scan a bounded review/previous-alert set from the conflict collection."""

        bounded = max(1, min(int(limit), 100))
        cursor = (
            self._mongo.db[_CONFLICT_COLLECTION]
            .find(
                {
                    "$or": [
                        {"application_status": OPERATOR_REVIEW},
                        {"operational_alerts.operator_review.active": True},
                    ]
                }
            )
            .sort([("updated_at", 1), ("_id", 1)])
            .limit(bounded)
        )
        rows = await cursor.to_list(length=bounded)
        for record in rows:
            await self.observe_conflict_claim(record)
        return len(rows)

    @staticmethod
    def _backlog_query(now: datetime, due_phases: Iterable[str]) -> dict[str, Any]:
        return {
            "application_status": {"$in": list(due_phases)},
            "$or": [
                {"retry_due_at": {"$lte": now}},
                {
                    "retry_due_at": {"$exists": False},
                    "provider_hostname_id": {"$type": "string"},
                },
                {
                    "retry_due_at": None,
                    "provider_hostname_id": {"$type": "string"},
                },
            ],
        }

    async def observe_backlog(self, due_phases: Iterable[str]) -> None:
        """Publish queue depth and oldest-age gauges with a bounded sample."""

        now = self._now()
        domains = self._mongo.db["storefront_domains"]
        count_documents = getattr(domains, "count_documents", None)
        if not callable(count_documents):
            return
        query = self._backlog_query(now, due_phases)
        count = int(await count_documents(query))
        rows = await (
            domains.find(query, {"retry_due_at": 1, "updated_at": 1})
            .sort([("retry_due_at", 1), ("updated_at", 1)])
            .limit(_BACKLOG_SAMPLE_LIMIT)
            .to_list(length=_BACKLOG_SAMPLE_LIMIT)
        )
        due_times = [
            value
            for row in rows
            if (
                value := (
                    _aware(row.get("retry_due_at")) or _aware(row.get("updated_at"))
                )
            )
            is not None
        ]
        oldest_age = (
            max(0.0, (now - min(due_times)).total_seconds()) if due_times else 0.0
        )
        await self._set_metric(
            "storefront.domain.reconciliation.backlog_count", float(count)
        )
        await self._set_metric(
            "storefront.domain.reconciliation.backlog_oldest_age_seconds",
            oldest_age,
        )
        await self._observe_backlog_alert(count, oldest_age)
