#!/usr/bin/env bash
# ──────────────────────────────────────────────────────────────────────
# generate_types.sh — Automated Pydantic → TypeScript type generation
#
# Best Practice Reference:
#   pydantic-to-typescript (https://github.com/phillipdupuis/pydantic-to-typescript)
#   "Use a single source of truth for type definitions across Python and
#    TypeScript. Integrate the code generation process into your CI/CD
#    pipeline to keep TypeScript interfaces up-to-date automatically."
#
# Usage:
#   ./scripts/generate_types.sh          # Generate all types
#   ./scripts/generate_types.sh --check  # CI mode: fail if types are stale
# ──────────────────────────────────────────────────────────────────────
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(dirname "$SCRIPT_DIR")"
OUTPUT_DIR="$PROJECT_ROOT/app/types/generated"
MODELS_DIR="$PROJECT_ROOT/app/models"

# Ensure output directory exists
mkdir -p "$OUTPUT_DIR"

# Check if pydantic2ts is installed
if ! command -v pydantic2ts &> /dev/null; then
    echo "⚠️  pydantic2ts not found. Installing..."
    pip install 'pydantic-to-typescript>=2' --break-system-packages -q
fi

# Check if json2ts is installed (required by pydantic2ts)
if ! command -v json2ts &> /dev/null; then
    echo "⚠️  json2ts not found. Installing..."
    npm install -g json-schema-to-typescript -q
fi

echo "📦 Generating TypeScript interfaces from Pydantic models..."

# Map of Python model modules → TypeScript output files
# Add new models here as the project grows
declare -A MODEL_MAP=(
    ["app.models.guest"]="guest.ts"
    ["app.models.table"]="table.ts"
    ["app.models.form"]="form.ts"
    ["app.models.subscription"]="subscription.ts"
    ["app.models.budget"]="budget.ts"
    ["app.models.rsvp"]="rsvp.ts"
    ["app.models.plus_one"]="plus_one.ts"
    ["app.models.planner_notification"]="planner_notification.ts"
    ["app.models.calendar"]="calendar.ts"
    ["app.models.blog"]="blog.ts"
)

FAILED=0

for module in "${!MODEL_MAP[@]}"; do
    output_file="${MODEL_MAP[$module]}"
    echo "  → $module → $OUTPUT_DIR/$output_file"

    if ! pydantic2ts \
        --module "$module" \
        --output "$OUTPUT_DIR/$output_file" \
        2>/dev/null; then
        echo "  ⚠️  Failed to generate $output_file (module may have runtime deps)"
        FAILED=$((FAILED + 1))
    fi
done

# Add auto-generated header to each file
for ts_file in "$OUTPUT_DIR"/*.ts; do
    if [ -f "$ts_file" ]; then
        HEADER="/* Auto-generated by pydantic-to-typescript. DO NOT EDIT MANUALLY.\n * Source: Pydantic models in app/models/\n * Run: ./scripts/generate_types.sh\n */\n"
        # Only add header if not already present
        if ! head -1 "$ts_file" | grep -q "Auto-generated"; then
            TEMP=$(mktemp)
            printf "$HEADER" > "$TEMP"
            cat "$ts_file" >> "$TEMP"
            mv "$TEMP" "$ts_file"
        fi
    fi
done

echo ""
echo "✅ Type generation complete. $FAILED modules skipped."

# CI mode: check if generated types differ from committed versions
if [[ "${1:-}" == "--check" ]]; then
    echo ""
    echo "🔍 Checking for type drift..."
    cd "$PROJECT_ROOT"
    if git diff --quiet -- "$OUTPUT_DIR"; then
        echo "✅ Types are up to date."
    else
        echo "❌ Generated types differ from committed versions!"
        echo "   Run './scripts/generate_types.sh' and commit the changes."
        git diff --stat -- "$OUTPUT_DIR"
        exit 1
    fi
fi
